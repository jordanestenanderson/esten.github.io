#!/usr/bin/env python3
"""Refresh dimensions used by the portfolio image template."""

import json
import re
import subprocess
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
PORTFOLIO = ROOT / "assets" / "portfolio"
OUTPUT = ROOT / "_data" / "image_dimensions.yml"


def dimensions_for(folder):
    images = sorted(
        path for path in folder.iterdir() if path.suffix.lower() in {".jpg", ".jpeg", ".png"}
    )
    result = subprocess.run(
        ["sips", "-g", "pixelWidth", "-g", "pixelHeight", *(str(path) for path in images)],
        check=True,
        capture_output=True,
        text=True,
    )

    dimensions = {}
    current = None
    for line in result.stdout.splitlines():
        if line.startswith(str(folder)):
            current = Path(line).name
            dimensions[current] = {}
        elif current and (match := re.match(r"\s*pixel(Width|Height): (\d+)", line)):
            dimensions[current][match.group(1).lower()] = int(match.group(2))

    if len(dimensions) != len(images) or any(len(size) != 2 for size in dimensions.values()):
        raise RuntimeError(f"Could not read every image in {folder}")
    return dimensions


lines = ["# Generated by _scripts/update-image-dimensions.py. Rerun after adding portfolio images."]
for folder in sorted(path for path in PORTFOLIO.iterdir() if path.is_dir() and path.name != "archive"):
    lines.append(f"{folder.name}:")
    for name, size in sorted(dimensions_for(folder).items()):
        lines.append(f"  {json.dumps(name)}: [{size['width']}, {size['height']}]")

OUTPUT.parent.mkdir(exist_ok=True)
OUTPUT.write_text("\n".join(lines) + "\n")
